function isLegacyFeiyuPrompt(normalized: string): boolean {
  const fingerprint = LEGACY_FEIYU_PROMPT_FINGERPRINTS[normalized.length];
  return typeof fingerprint === 'number' && presetFingerprint(normalized) === fingerprint;
}

export function upgradeFeiyuPrompt(prompt?: string): string {
  const normalized = typeof prompt === 'string' ? prompt.replace(/\r\n/g, '\n').trim() : '';
  // Only replace the exact old built-in sheets; preserve custom additions and edits.
  if (!normalized || isLegacyFeiyuPrompt(normalized)) {
    return FEIYU_DEFAULT_PERSONA_PROMPT;
  }
  return prompt!;
}

